type Translate = (key: string, replacements?: Record<string, string | number>) => string

export function translateComplianceReason(reason: string, t: Translate): string {
  const exact: Record<string, string> = {
    'Item is archived': 'archived',
    'No datasheet uploaded': 'noDatasheet',
    'No supplier information provided': 'noSupplierInformation',
    'No dietary attributes entered (e.g. Vegan, Gluten-Free)': 'noDietaryAttributes',
    'No review date set - needs initial review': 'noReviewDate',
    'No manufacturer datasheet or label evidence uploaded': 'noManufacturerEvidence',
    'No ingredient declaration recorded from the pack': 'noIngredientDeclaration',
    'Label details have not been verified': 'labelNotVerified',
    'No supplier linked': 'noSupplierLinked',
    'No menu item review date set': 'noMenuReviewDate',
  }

  const exactKey = exact[reason]
  if (exactKey) return t(`complianceDocuments.${exactKey}`)

  let match = reason.match(/^Review overdue by (\d+) days \(last reviewed (\d+) days ago\)$/)
  if (match) return t('complianceDocuments.reviewOverdue', { overdue: match[1], elapsed: match[2] })

  match = reason.match(/^Review due in (\d+) days$/)
  if (match) return t('complianceDocuments.reviewDue', { days: match[1] })

  match = reason.match(/^(\d+) ingredient\(s\) not compliant - review ingredient\(s\) first$/)
  if (match) return t('complianceDocuments.ingredientsNotCompliant', { count: match[1] })

  match = reason.match(/^Ingredient review overdue by (\d+) days$/)
  if (match) return t('complianceDocuments.ingredientReviewOverdue', { days: match[1] })

  match = reason.match(/^Menu item review overdue by (\d+) days$/)
  if (match) return t('complianceDocuments.menuReviewOverdue', { days: match[1] })

  match = reason.match(/^Menu item review due in (\d+) days$/)
  if (match) return t('complianceDocuments.menuReviewDue', { days: match[1] })

  return reason
}
